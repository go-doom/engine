// harvest-reference is the R-doom1g provable-protocol oracle generator.
//
// It runs the gore engine HEADLESS, in deterministic mode (tic-locked
// clock + fixed PRNG seed), with a SCRIPTED input sequence supplied via
// flags, and snapshots the framebuffer + PRNG state + frame-hash at
// every declared checkpoint tic. The resulting files under -out form
// the reference oracle that internal/livedoomboot/provable_test.sh
// compares against on every CI run.
//
// Reproducibility contract (the whole point):
//
//   - Same WAD bytes + same -seed + same -script + same gore commit
//     ==> identical oracle bytes (PPM + JSON + SHA-256).
//   - If the WAD or gore commit changes, the oracle is regenerated by
//     re-running this command; the resulting diff in the oracle/
//     directory is committed atomically with the engine/WAD bump, so
//     every revision of the oracle is auditable in git history.
//
// Why this is provable, not empirical:
//
//   - The framebuffer at tic T is a pure function of (initial WAD,
//     seed, input sequence up to T, engine version). Two runs that
//     match on every input MUST produce byte-identical frames.
//   - The frame SHA-256 hash collapses the provability check to a
//     32-byte constant-time compare in CI.
//
// Usage:
//
//	harvest-reference \
//	    -wad embedwad/doom1.wad \
//	    -seed 0 \
//	    -script docs/oracle-script.txt \
//	    -checkpoints 105,175,350,525,1050 \
//	    -out oracle/
//
// The script file format is one event per line:
//
//	<tic>:keydown:<KEY>     # KEY is a gore.KEY_* symbol or hex
//	<tic>:keyup:<KEY>
//	<tic>:end               # tell the engine to Stop()
//
// Comments (#…) and blank lines are skipped.

